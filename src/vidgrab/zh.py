def _build_map() -> dict[str, str]:
    table: dict[str, str] = {}
    for chunk in _PAIRS.split():
        if len(chunk) == 2:
            table[chunk[0]] = chunk[1]
    return table


_MAP = _build_map()


def to_simplified(text: str) -> str:
    """把繁體字轉成簡體。沒收錄的字原樣保留（寧可漏轉，不要轉錯）。"""
    if not text:
        return text
    return "".join(_MAP.get(ch, ch) for ch in text)


def is_conversion_meaningful(text: str) -> bool:
    """這段文字真的含有可轉換的繁體字嗎？"""
    return any(ch in _MAP for ch in (text or ""))


def search_forms(keyword: str) -> list[str]:
    """回傳要拿去搜尋的所有寫法，原文一定排第一。

    呼叫端應該全部都搜、取聯集——這樣對照表不完整也不會少結果。
    """
    out = [(keyword or "").strip()]
    simp = to_simplified(keyword)
    if simp and simp not in out:
        out.append(simp)
    return [k for k in out if k]
